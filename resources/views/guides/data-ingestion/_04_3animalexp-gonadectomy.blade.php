<h4 id="gonadectomy-procedure">Gonadectomy Procedure</h4>
<p>If your study involves a gonadectomy procedure, check the box "Performs a gonadectomy" in the Setup questions. This will activate the Gonadectomy Procedure component within the form.</p>

<h5>Adding a Gonadectomy Procedure:</h5>
<p>To create a gonadectomy procedure entry (Figure 13), click the "+ Add Procedure" button. This opens a window with three fields:</p>

<ol>
    <li><strong>Procedure Type (required):</strong> Select from the dropdown menu:
        <ul>
            <li><strong>Ovariectomy:</strong> Surgical removal of ovaries</li>
            <li><strong>Orchiectomy:</strong> Surgical removal of testes</li>
            <li><strong>Sham Surgery:</strong> Control procedure involving anesthesia and incision without gonad removal</li>
            <li><strong>No Surgery:</strong> Control group with no surgical intervention</li>
        </ul>
    </li>

    <li><strong>Age at Surgery (required):</strong> Enter the age of the animals (in weeks) at the time the procedure was performed.</li>
    <li><strong>Description (optional):</strong> Use this text box to provide additional details about the surgical procedure, such as anesthesia protocols, post-operative care, recovery time, or any relevant procedural notes.</li>
</ol>
<p>Once you have completed these fields, click the "+ Add" button to save the procedure. It will then appear in the Gonadectomy Procedures table.</p>

<h5>Adding Multiple Procedures:</h5>
<p>If your study includes multiple gonadectomy groups (for example, surgery at different ages, or both ovariectomy and sham control groups), click the "+ Add Procedure" button below the table and repeat the process for each additional procedure group. All procedures you create will be available later in the form when you define the sample groups that underwent phenotypic analysis.</p>

