<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class StatisticsJob extends Model
{
    protected $fillable = [
        'sample_group_id',
        'comparison_group_id',
        'analysis_type_id',
        'specimen_type_id',
        'analyte_category_id',
        'region_id',
        'test_method',
        'bone_tested',
        'status',
        'processing_version',
        'measurements_count',
        'completed_at',
        'error_message',
    ];

    protected $casts = [
        'completed_at' => 'datetime',
        'measurements_count' => 'integer',
    ];

    // computed column - generated by database
    protected $appends = [];
    // context key is computed by database - not fillable

    public function sampleGroup(): BelongsTo
    {
        return $this->belongsTo(SampleGroup::class);
    }

    public function comparisonGroup(): BelongsTo
    {
        return $this->belongsTo(ComparisonGroup::class);
    }

    public function analysisType(): BelongsTo
    {
        return $this->belongsTo(AnalysisType::class);
    }

    public function specimenType(): BelongsTo
    {
        return $this->belongsTo(SpecimenType::class);
    }

    public function analyteCategory(): BelongsTo
    {
        return $this->belongsTo(AnalyteCategory::class);
    }

    public function descriptiveStatistics(): HasMany
    {
        return $this->hasMany(DescriptiveStatistic::class);
    }

    public function inferentialStatistics(): HasMany
    {
        return $this->hasMany(InferentialStatistic::class);
    }

    // scopes
    public function scopeDescriptive($query)
    {
        return $query->whereNotNull('sample_group_id')->whereNull('comparison_group_id');
    }

    public function scopeInferential($query)
    {
        return $query->whereNull('sample_group_id')->whereNotNull('comparison_group_id');
    }

    public function scopeCompleted($query)
    {
        return $query->where('status', 'completed');
    }

    public function scopeFailed($query)
    {
        return $query->where('status', 'failed');
    }

    public function scopePending($query)
    {
        return $query->where('status', 'pending');
    }

    public function scopeProcessing($query)
    {
        return $query->where('status', 'processing');
    }

    public function scopeForContext($query, array $context)
    {
        return $query
            ->where('analysis_type_id', $context['analysis_type_id'])
            ->where('specimen_type_id', $context['specimen_type_id'])
            ->where('analyte_category_id', $context['analyte_category_id'])
            ->where('region_id', $context['region_id'])
            ->where('test_method', $context['test_method'])
            ->where('bone_tested', $context['bone_tested']);
    }

    // helper methods
    public function isDescriptive(): bool
    {
        return $this->sample_group_id !== null && $this->comparison_group_id === null;
    }

    public function isInferential(): bool
    {
        return $this->comparison_group_id !== null && $this->sample_group_id === null;
    }

    public function getContext(): array
    {
        return [
            'analysis_type_id' => $this->analysis_type_id,
            'specimen_type_id' => $this->specimen_type_id,
            'analyte_category_id' => $this->analyte_category_id,
            'region_id' => $this->region_id,
            'test_method' => $this->test_method,
            'bone_tested' => $this->bone_tested,
        ];
    }
}
